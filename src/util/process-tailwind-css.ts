import postcss from "postcss";
import { createTailwindcssPlugin } from ".";
import { resolveCSSVariables } from "./tailwind-variable-resolver";

// Extract only the CSS rules for the requested classes
function extractRequestedClasses(fullCSS: string, content: string): string {
  // Parse the class names from the content
  const classNames = content.trim().split(/\s+/).filter(cls => cls.length > 0);
  
  // Parse the full CSS
  const root = postcss.parse(fullCSS);
  const extractedRules: string[] = [];
  const extractedProperties: string[] = [];
  
  // Walk through all rules and extract matching ones
  root.walkRules((rule) => {
    const selector = rule.selector;
    
    // Check if this rule matches any of our requested classes
    const matchesRequestedClass = classNames.some(className => {
      // The CSS contains escaped selectors like .w-2\.5 and .dark\:border-gray-700
      // We need to match against the actual escaped versions
      const cssEscapedClassName = className.replace(/\./g, '\\.').replace(/:/g, '\\:');
      
      // Match exact class selectors including CSS-escaped versions
      return selector === `.${className}` ||                    // exact match (for simple classes)
             selector === `.${cssEscapedClassName}` ||          // CSS-escaped match (e.g., .w-2\.5)
             selector.includes(`.${className}:`) ||              // pseudo-classes
             selector.includes(`.${className}\\:`) ||            // escaped colons in original
             selector.includes(`.${cssEscapedClassName}`) ||     // CSS-escaped special chars
             selector.includes(`.${className}[`) ||              // attribute selectors
             selector.includes(`.${className} `) ||              // descendant selectors
             selector.includes(`.${className}.`) ||              // multi-class selectors
             selector.endsWith(`.${className}`) ||               // class at end
             selector.endsWith(`.${cssEscapedClassName}`);       // CSS-escaped class at end
    });
    
    if (matchesRequestedClass) {
      extractedRules.push(rule.toString());
    }
  });
  
  // Walk through @property rules and other at-rules that might be needed
  root.walkAtRules((atRule) => {
    // Include @property rules as they're needed for CSS custom properties
    if (atRule.name === 'property') {
      extractedProperties.push(atRule.toString());
    }
  });
  
  // Combine the extracted rules and properties
  return [...extractedRules, ...extractedProperties].join('\n');
}

export const processTailwindCSS = async (
  props: {
    inputCSS?: string;
    content: string;
  }
): Promise<string | null> => {
  // Parse the class names from the content to check if we're processing a single class
  const classNames = props.content.trim().split(/\s+/).filter(cls => cls.length > 0);
  
  // If processing a single class, we can detect "not found" vs "no matching styles"
  if (classNames.length === 1) {
    const singleClassName = classNames[0];
    
    // Create a plugin that directly checks if the class generates CSS
    const checkClassPlugin = createTailwindcssPlugin({
      inputCSS: props.inputCSS,
      content: singleClassName,
    });

    const cssInput = props.inputCSS || `/* Tailwind v4 - CSS will be generated by plugin */`;
    const processor = postcss([checkClassPlugin]);
    const result = await processor.process(cssInput, { 
      from: undefined
    });
    
    // Extract only the CSS rules for the requested class
    const extractedCSS = extractRequestedClasses(result.css, singleClassName);
    
    // Only return null if absolutely no CSS was generated 
    // (not even from custom classes or @layer components)
    if (!extractedCSS || extractedCSS.trim() === '') {
      return null; // Truly no CSS found for this class
    }
    
    // Apply variable resolution to the extracted CSS
    // We need to get the design system for variable resolution
    try {
      const { __unstable__loadDesignSystem } = await import('tailwindcss');
      const inputCSS = props.inputCSS || `@import "tailwindcss";`;
      
      // Simple loadStylesheet for variable resolution (we don't need full CSS loading here)
      const loadStylesheet = async (id: string) => {
        if (id === 'tailwindcss') {
          const { TAILWIND_V4_CSS } = await import('./tailwind-v4-css');
          return { path: id, base: '', content: TAILWIND_V4_CSS };
        }
        return { path: id, base: '', content: '' };
      };
      
      const designSystem = await __unstable__loadDesignSystem(inputCSS, { loadStylesheet });
      const resolvedCSS = await resolveCSSVariables(extractedCSS, designSystem);
      return resolvedCSS;
    } catch (error: any) {
      console.warn('Variable resolution failed for single class:', (error as any)?.message);
      return extractedCSS; // Return unresolved CSS as fallback
    }
  }
  
  // For multiple classes, use the original approach (can't distinguish individual not-found)
  const tailwindcssPlugin = createTailwindcssPlugin({
    inputCSS: props.inputCSS,
    content: props.content,
  });

  const cssInput = props.inputCSS || `/* Tailwind v4 - CSS will be generated by plugin */`;
  const processor = postcss([tailwindcssPlugin]);
  const result = await processor.process(cssInput, { 
    from: undefined
  });
  
  // Extract only the CSS rules for the requested classes
  const extractedCSS = extractRequestedClasses(result.css, props.content);
  
  // Apply variable resolution to the extracted CSS
  try {
    const { __unstable__loadDesignSystem } = await import('tailwindcss');
    const inputCSS = props.inputCSS || `@import "tailwindcss";`;
    
    // Simple loadStylesheet for variable resolution
    const loadStylesheet = async (id: string) => {
      if (id === 'tailwindcss') {
        const { TAILWIND_V4_CSS } = await import('./tailwind-v4-css');
        return { path: id, base: '', content: TAILWIND_V4_CSS };
      }
      return { path: id, base: '', content: '' };
    };
    
    const designSystem = await __unstable__loadDesignSystem(inputCSS, { loadStylesheet });
    const resolvedCSS = await resolveCSSVariables(extractedCSS, designSystem);
    return resolvedCSS;
  } catch (error: any) {
    console.warn('Variable resolution failed for multiple classes:', (error as any)?.message);
    return extractedCSS; // Return unresolved CSS as fallback
  }
};
